import { z } from 'zod';
import { ACCOUNT_TYPES, DOCUMENT_TYPES } from '../constants';
import { isValidGSTIN } from '../gst';

export const createPartySchema = z.object({
  kind: z.enum(['customer', 'vendor', 'both']),
  name: z.string().min(1, 'Party name is required'),
  gstin: z
    .string()
    .optional()
    .nullable()
    .refine((val) => !val || isValidGSTIN(val), { message: 'Invalid GSTIN format' }),
  phone: z.string().optional().nullable(),
  email: z.string().email().optional().nullable().or(z.literal('')),
  address: z.string().optional().nullable(),
  creditDays: z.number().int().min(0).default(0),
  openingBalance: z.number().int().default(0), // in paise
  isActive: z.boolean().default(true),
});
export type CreatePartyInput = z.infer<typeof createPartySchema>;

export const createItemSchema = z.object({
  name: z.string().min(1, 'Item name is required'),
  hsnSac: z.string().optional().nullable(),
  unit: z.string().default('Nos'),
  salePrice: z.number().int().min(0).default(0), // in paise
  purchasePrice: z.number().int().min(0).default(0), // in paise
  gstRate: z.number().min(0).max(100).default(0),
  trackStock: z.boolean().default(false),
  stockQty: z.number().default(0),
});
export type CreateItemInput = z.infer<typeof createItemSchema>;

export const createAccountSchema = z.object({
  code: z.string().min(1, 'Account code is required'),
  name: z.string().min(1, 'Account name is required'),
  type: z.enum(ACCOUNT_TYPES),
  parentId: z.string().uuid().optional().nullable(),
});
export type CreateAccountInput = z.infer<typeof createAccountSchema>;

export const documentLineSchema = z.object({
  itemId: z.string().optional().nullable(),
  description: z.string().min(1, 'Description is required'),
  hsnSac: z.string().optional().nullable(),
  unit: z.string().optional().default('PCS'),
  qty: z.number().positive('Quantity must be greater than 0'),
  rate: z.number().int().nonnegative('Rate must be non-negative'), // in paise
  discount: z.number().int().nonnegative().default(0), // in paise
  gstRate: z.number().min(0).max(100).default(0),
  cgst: z.number().int().default(0),
  sgst: z.number().int().default(0),
  igst: z.number().int().default(0),
  lineTotal: z.number().int(),
});
export type DocumentLineInput = z.infer<typeof documentLineSchema>;

export const createDocumentSchema = z.object({
  docType: z.enum(DOCUMENT_TYPES),
  docNo: z.string().optional(), // generated by server if omitted
  docDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Date must be YYYY-MM-DD'),
  dueDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/, 'Date must be YYYY-MM-DD').optional().nullable(),
  partyId: z.string().min(1, 'Party is required'),
  placeOfSupply: z.string().min(2, 'Place of supply state code is required'),
  subtotal: z.number().int(),
  taxTotal: z.number().int(),
  roundOff: z.number().int().default(0),
  total: z.number().int(),
  lines: z.array(documentLineSchema).min(1, 'At least one line item is required'),
});
export type CreateDocumentInput = z.infer<typeof createDocumentSchema>;

export const journalLineSchema = z.object({
  accountId: z.string().min(1, 'Account is required'),
  partyId: z.string().optional().nullable(),
  debit: z.number().int().nonnegative().default(0),
  credit: z.number().int().nonnegative().default(0),
}).refine(
  (data) => (data.debit > 0 && data.credit === 0) || (data.credit > 0 && data.debit === 0),
  { message: 'Line must have either debit or credit, not both or neither' }
);
export type JournalLineInput = z.infer<typeof journalLineSchema>;

export const createJournalEntrySchema = z.object({
  entryDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  narration: z.string().optional().nullable(),
  lines: z.array(journalLineSchema).min(2, 'Journal entry requires at least 2 lines'),
}).refine(
  (data) => {
    const totalDebit = data.lines.reduce((acc, l) => acc + l.debit, 0);
    const totalCredit = data.lines.reduce((acc, l) => acc + l.credit, 0);
    return totalDebit === totalCredit && totalDebit > 0;
  },
  { message: 'Total debits must equal total credits and be greater than 0' }
);
export type CreateJournalEntryInput = z.infer<typeof createJournalEntrySchema>;

export const createPaymentReceiptSchema = z.object({
  kind: z.enum(['receipt', 'payment']),
  partyId: z.string().min(1, 'Party is required'),
  payDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  mode: z.enum(['cash', 'bank', 'upi', 'cheque']),
  bankAccountId: z.string().optional().nullable(),
  chequeId: z.string().optional().nullable(),
  amount: z.number().int().positive('Amount must be positive'),
  reference: z.string().optional().nullable(),
  allocations: z.array(
    z.object({
      documentId: z.string().min(1),
      amount: z.number().int().positive(),
    })
  ).optional(),
});
export type CreatePaymentReceiptInput = z.infer<typeof createPaymentReceiptSchema>;
